"""Risk decision policy: hard rules dominate the LLM; LLM failures degrade safely."""
from dataclasses import dataclass
from app.ai.schemas import RiskAnalysis, Verdict

@dataclass(frozen=True)
class Decision:
    verdict: Verdict
    risk_level: str
    reasons: list[str]
    decision_source: str


def decide_verdict(flags: dict[str, bool], rule_reasons: list[str], llm_result: RiskAnalysis | None) -> Decision:
    reasons = list(rule_reasons)
    source = "rules-only"
    # Hard rules cannot be lowered by the LLM.
    if flags.get("duplicate") or flags.get("velocity_breach"):
        hard_reasons = []
        if flags.get("duplicate"):
            hard_reasons.append("Hard rule: recent duplicate payment pattern")
        if flags.get("velocity_breach"):
            hard_reasons.append("Hard rule: payment velocity threshold exceeded")
        return Decision("bark", "high", list(dict.fromkeys(reasons + hard_reasons)), source)

    if llm_result is not None:
        source = "rules+llm"
        risk = llm_result.risk_level
        reasons.extend(llm_result.reasons)
        # Rule-derived amount anomalies cannot be erased by the LLM.
        if flags.get("amount_outlier") and risk == "low":
            risk = "medium"
            reasons.append("Risk raised to medium because the merchant amount baseline was exceeded")
    else:
        # Conservative and explicit rules-only fallback for an outlier.
        risk = "medium" if flags.get("amount_outlier") else "low"
        if flags.get("amount_outlier"):
            reasons.append("Rules-only fallback: unusual amount requires merchant review")
        reasons.append("LLM unavailable or disabled; decision generated by deterministic rules only")

    mapping: dict[str, Verdict] = {"low": "wag", "medium": "growl", "high": "bark"}
    reasons = list(dict.fromkeys(reasons))[:8]
    return Decision(mapping[risk], risk, reasons or ["No high-risk signals detected by configured checks"], source)
